package assistant

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"net/http"
	"os"
	"strings"
	"time"
)

// AIConfig holds endpoint and authentication details for the AI diagnostics gateway.
type AIConfig struct {
	Endpoint string `json:"endpoint"` // e.g. "http://localhost:4000/v1/chat/completions" or "http://localhost:11434/v1/chat/completions"
	Model    string `json:"model"`    // e.g. "gemini-1.5-flash", "llama3", or "gpt-4o-mini"
	APIKey   string `json:"apiKey,omitempty"`
}

// DefaultAIConfig returns sensible local-first AI gateway defaults.
func DefaultAIConfig() AIConfig {
	endpoint := os.Getenv("CATALYST_AI_ENDPOINT")
	if endpoint == "" {
		endpoint = "http://localhost:4000/v1/chat/completions" // LiteLLM default gateway
	}
	model := os.Getenv("CATALYST_AI_MODEL")
	if model == "" {
		model = "gemini-1.5-flash"
	}
	return AIConfig{
		Endpoint: endpoint,
		Model:    model,
		APIKey:   os.Getenv("CATALYST_AI_KEY"),
	}
}

// AIExplanation contains structured guidance generated by the AI gateway.
type AIExplanation struct {
	Available   bool   `json:"available"`
	RootCause   string `json:"rootCause"`
	SuggestedFix string `json:"suggestedFix"`
	CodeSnippet string `json:"codeSnippet,omitempty"`
	Error       string `json:"error,omitempty"`
}

// ExplainError requests an AI-generated explanation for an error snippet.
func ExplainError(ctx context.Context, cfg AIConfig, errorLogs, projectType string) AIExplanation {
	if cfg.Endpoint == "" {
		return AIExplanation{
			Available: false,
			Error:     "AI gateway endpoint not configured",
		}
	}

	prompt := fmt.Sprintf(`You are an expert developer assistant. Analyze this build or runtime error from a %s project and provide:
1. Root cause summary (1-2 sentences).
2. Actionable fix steps.
3. Code or command snippet to resolve it.

Error output:
%s`, projectType, errorLogs)

	reqPayload := map[string]interface{}{
		"model": cfg.Model,
		"messages": []map[string]string{
			{"role": "system", "content": "You are Catalyst AI, a concise and precise development companion."},
			{"role": "user", "content": prompt},
		},
		"temperature": 0.2,
		"max_tokens":  500,
	}

	data, err := json.Marshal(reqPayload)
	if err != nil {
		return AIExplanation{Available: false, Error: err.Error()}
	}

	client := &http.Client{Timeout: 8 * time.Second}
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, cfg.Endpoint, bytes.NewReader(data))
	if err != nil {
		return AIExplanation{Available: false, Error: err.Error()}
	}

	req.Header.Set("Content-Type", "application/json")
	if cfg.APIKey != "" {
		req.Header.Set("Authorization", "Bearer "+cfg.APIKey)
	}

	resp, err := client.Do(req)
	if err != nil {
		return AIExplanation{
			Available: false,
			Error:     "AI gateway unreachable (ensure local AI service is running on " + cfg.Endpoint + ")",
		}
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return AIExplanation{
			Available: false,
			Error:     fmt.Sprintf("AI gateway returned HTTP %d", resp.StatusCode),
		}
	}

	var res struct {
		Choices []struct {
			Message struct {
				Content string `json:"content"`
			} `json:"message"`
		} `json:"choices"`
	}

	if err := json.NewDecoder(resp.Body).Decode(&res); err != nil || len(res.Choices) == 0 {
		return AIExplanation{Available: false, Error: "Invalid response from AI gateway"}
	}

	content := strings.TrimSpace(res.Choices[0].Message.Content)

	return AIExplanation{
		Available:    true,
		RootCause:    "AI Diagnosis Generated",
		SuggestedFix: content,
	}
}
